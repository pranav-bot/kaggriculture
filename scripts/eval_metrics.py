#!/usr/bin/env python3
"""Metrics and report formatting for seed-matched replay evaluations."""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Iterable


@dataclass
class EvaluationResult:
    replay: str
    seed: Any
    candidate_cash: float | None = None
    surrogate_cash: float | None = None
    replay_opponent_cash: float | None = None
    exact_turns: int = 0
    surrogate_turns: int = 0
    noop_turns: int = 0
    malformed_turns: int = 0
    diverged_turns: int = 0
    total_opponent_turns: int = 0
    error: str | None = None
    notes: list[str] = field(default_factory=list)

    @property
    def seed_matched_delta(self) -> float | None:
        if self.candidate_cash is None or self.surrogate_cash is None:
            return None
        return self.candidate_cash - self.surrogate_cash

    @property
    def counterfactual_margin(self) -> float | None:
        if self.candidate_cash is None or self.replay_opponent_cash is None:
            return None
        return self.candidate_cash - self.replay_opponent_cash

    @property
    def divergence_rate(self) -> float:
        if not self.total_opponent_turns:
            return 0.0
        return self.diverged_turns / self.total_opponent_turns

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data.update(
            seed_matched_delta=self.seed_matched_delta,
            counterfactual_margin=self.counterfactual_margin,
            divergence_rate=self.divergence_rate,
        )
        return data


def aggregate(results: Iterable[EvaluationResult]) -> dict[str, Any]:
    rows = list(results)
    valid = [r for r in rows if r.error is None]

    def mean(name: str) -> float | None:
        values = [getattr(r, name) for r in valid if getattr(r, name) is not None]
        return sum(values) / len(values) if values else None

    turns = sum(r.total_opponent_turns for r in rows)
    return {
        "replays": len(rows),
        "valid_replays": len(valid),
        "failed_replays": len(rows) - len(valid),
        "mean_candidate_cash": mean("candidate_cash"),
        "mean_surrogate_cash": mean("surrogate_cash"),
        "mean_replay_opponent_cash": mean("replay_opponent_cash"),
        "mean_seed_matched_delta": mean("seed_matched_delta"),
        "mean_counterfactual_margin": mean("counterfactual_margin"),
        "divergence_rate": (
            sum(r.diverged_turns for r in rows) / turns if turns else 0.0
        ),
        "exact_turns": sum(r.exact_turns for r in rows),
        "surrogate_turns": sum(r.surrogate_turns for r in rows),
        "noop_turns": sum(r.noop_turns for r in rows),
        "malformed_turns": sum(r.malformed_turns for r in rows),
        "diverged_turns": sum(r.diverged_turns for r in rows),
        "total_opponent_turns": turns,
    }


def write_markdown(path: str | Path, results: Iterable[EvaluationResult]) -> None:
    rows = list(results)
    summary = aggregate(rows)
    lines = [
        "# Replay Evaluation Results",
        "",
        "Generated by `scripts/eval_runner.py`.",
        "",
        "## Definitions and assumptions",
        "",
        "- **Seed-Matched Delta** = candidate terminal cash minus the deterministic "
        "surrogate terminal cash on the same replay seed.",
        "- **Counterfactual Margin** = candidate terminal cash minus the recorded "
        "replay opponent's terminal cash. It is descriptive, not a claim that the "
        "recorded opponent can be reproduced exactly.",
        "- **Divergence Rate** = turns requiring surrogate or safe-no-op fallback "
        "(including missing/malformed replay frames) divided by opponent turns.",
        "- Replay actions use the observed `step + 1` offset documented in "
        "`research/recon_findings.md`; a PASS action is used after the replay.",
        "- Terminal cash is farm money only; inventory and carried goods are not "
        "liquidated implicitly.",
        "",
        "## Aggregate",
        "",
        f"- Replays: {summary['valid_replays']}/{summary['replays']} valid",
        f"- Mean candidate cash: {summary['mean_candidate_cash']}",
        f"- Mean surrogate cash: {summary['mean_surrogate_cash']}",
        f"- Mean Seed-Matched Delta: {summary['mean_seed_matched_delta']}",
        f"- Mean Counterfactual Margin: {summary['mean_counterfactual_margin']}",
        f"- Divergence Rate: {summary['divergence_rate']:.2%}",
        f"- Tier counts: exact={summary['exact_turns']}, "
        f"surrogate={summary['surrogate_turns']}, no-op={summary['noop_turns']}",
        "",
        "## Per replay",
        "",
        "| Replay | Seed | Candidate | Surrogate | Delta | Margin | Divergence | Status |",
        "|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for r in rows:
        status = r.error or "ok"
        fmt = lambda value: "" if value is None else f"{value:,.2f}"
        lines.append(
            f"| `{r.replay}` | {r.seed} | {fmt(r.candidate_cash)} | "
            f"{fmt(r.surrogate_cash)} | {fmt(r.seed_matched_delta)} | "
            f"{fmt(r.counterfactual_margin)} | {r.divergence_rate:.2%} | {status} |"
        )
    lines += [
        "",
        "## Limitations and fixes",
        "",
        "The evaluator does not mutate simulator code. If Kaggle dependencies are "
        "unavailable, an explicit error is emitted and no result is presented as "
        "valid. Malformed actions fall back deterministically and are counted; "
        "unexpected simulator exceptions fail that replay rather than silently "
        "inventing terminal cash.",
        "",
    ]
    Path(path).write_text("\n".join(lines), encoding="utf-8")
